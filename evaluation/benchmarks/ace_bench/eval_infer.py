def process_git_patch(patch: Any) -> str:
    """Process and clean git patch.

    Args:
        patch: Raw patch content

    Returns:
        Cleaned patch string
    """
    if not isinstance(patch, str):
        return ''

    if not patch.strip():
        return ''

    patch = patch.replace('\r\n', '\n')

    # Find the first line that starts with "diff" and remove lines before it
    lines = patch.split('\n')
    for i, line in enumerate(lines):
        if line.startswith('diff --git'):
            patch = '\n'.join(lines[i:])
            break

    patch = patch.rstrip() + '\n'
    return patch


def get_instance_docker_image(instance_id: str) -> str:
    """Get Docker image name for the instance.

    Args:
        instance_id: Instance ID

    Returns:
        Docker image name
    """
    # TODO: 根据您的数据集格式确定docker image
    # 这里假设使用环境变量中的prefix
    default_prefix = os.environ.get('EVAL_DOCKER_IMAGE_PREFIX', 'docker.io/your-org/')
    image_name = f'ace.eval.{instance_id}'.replace('/', '_').replace(':', '_')
    return f'{default_prefix.rstrip("/")}/{image_name}'.lower()


def get_config(metadata: EvalMetadata, instance: pd.Series) -> OpenHandsConfig:
    """Get OpenHands configuration for evaluation.

    Args:
        metadata: Evaluation metadata
        instance: Instance data

    Returns:
        OpenHands configuration
    """
    # Determine docker image
    if 'docker_image' in instance:
        base_container_image = instance['docker_image']
    else:
        base_container_image = get_instance_docker_image(instance['instance_id'])

    logger.info(
        f'Using instance container image: {base_container_image}. '
        f'Please make sure this image exists.'
    )

    sandbox_config = get_default_sandbox_config_for_eval()
    sandbox_config.base_container_image = base_container_image

    # TODO: 如果需要动态资源因子，在此处设置
    # sandbox_config.remote_runtime_resource_factor = get_resource_factor(instance)

    config = get_openhands_config_for_eval(
        runtime=os.environ.get('RUNTIME', 'docker'),
        sandbox_config=sandbox_config,
    )

    return config


